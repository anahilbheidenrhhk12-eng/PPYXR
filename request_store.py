"""Persistent request tracking backed by Railway PostgreSQL or SQLite.

PostgreSQL is used when DATABASE_URL is set. Existing SQLite request records
are copied into PostgreSQL once and retained in the original SQLite file.
Verification URLs and documents are never stored.
"""
import os
import sqlite3
import threading
from datetime import datetime, timezone

_LOCK = threading.RLock()


def _path():
    folder = os.getenv("PPYXR_DATA_DIR") or os.getenv("DATA_DIR") or "/data"
    os.makedirs(folder, exist_ok=True)
    return os.path.join(folder, "ppy xr_requests.sqlite3".replace(" ", ""))


def _pg_url():
    return os.getenv("DATABASE_URL", "").strip()


def _postgres():
    import psycopg
    return psycopg.connect(_pg_url(), connect_timeout=15)


def _sqlite():
    connection = sqlite3.connect(_path(), timeout=20)
    connection.row_factory = sqlite3.Row
    return connection


def _migrate_legacy_sqlite(cur):
    legacy_path = _path()
    if not os.path.isfile(legacy_path):
        return
    with _sqlite() as old:
        try:
            rows = old.execute(
                "SELECT id, chat_id, link_count, status, created_at, updated_at FROM requests"
            ).fetchall()
        except sqlite3.OperationalError as exc:
            if "no such table" in str(exc).lower():
                return
            raise
    if rows:
        cur.executemany(
            """INSERT INTO requests
               (id, chat_id, link_count, status, created_at, updated_at)
               VALUES (%s, %s, %s, %s, %s, %s)
               ON CONFLICT (id) DO NOTHING""",
            [tuple(row) for row in rows],
        )
        # Ensure new records never overlap imported SQLite request IDs.
        cur.execute(
            """SELECT setval(
                   pg_get_serial_sequence('requests', 'id'),
                   COALESCE(MAX(id), 1), COUNT(*) > 0
               ) FROM requests"""
        )


def init_db():
    with _LOCK:
        if _pg_url():
            with _postgres() as conn:
                with conn.cursor() as cur:
                    cur.execute(
                        """CREATE TABLE IF NOT EXISTS requests (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            chat_id BIGINT NOT NULL,
                            link_count INTEGER NOT NULL,
                            status TEXT NOT NULL DEFAULT 'awaiting_official_verification',
                            created_at TEXT NOT NULL,
                            updated_at TEXT NOT NULL
                        )"""
                    )
                    cur.execute(
                        "CREATE INDEX IF NOT EXISTS requests_chat_idx ON requests(chat_id, id)"
                    )
                    _migrate_legacy_sqlite(cur)
            return

        with _sqlite() as conn:
            conn.execute(
                """CREATE TABLE IF NOT EXISTS requests (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    chat_id INTEGER NOT NULL,
                    link_count INTEGER NOT NULL,
                    status TEXT NOT NULL DEFAULT 'awaiting_official_verification',
                    created_at TEXT NOT NULL,
                    updated_at TEXT NOT NULL
                )"""
            )
            conn.execute(
                "CREATE INDEX IF NOT EXISTS requests_chat_idx ON requests(chat_id, id)"
            )


def submit(chat_id, link_count):
    now = datetime.now(timezone.utc).isoformat(timespec="seconds")
    with _LOCK:
        if _pg_url():
            with _postgres() as conn:
                with conn.cursor() as cur:
                    cur.execute(
                        """INSERT INTO requests
                           (chat_id, link_count, status, created_at, updated_at)
                           VALUES (%s, %s, 'awaiting_official_verification', %s, %s)
                           RETURNING id""",
                        (int(chat_id), int(link_count), now, now),
                    )
                    return cur.fetchone()[0]
        with _sqlite() as conn:
            cursor = conn.execute(
                """INSERT INTO requests (chat_id, link_count, status, created_at, updated_at)
                VALUES (?, ?, 'awaiting_official_verification', ?, ?)""",
                (int(chat_id), int(link_count), now, now),
            )
            return cursor.lastrowid


def get_for_user(chat_id, request_id):
    with _LOCK:
        if _pg_url():
            from psycopg.rows import dict_row
            with _postgres() as conn:
                with conn.cursor(row_factory=dict_row) as cur:
                    cur.execute(
                        """SELECT id, link_count, status, created_at
                           FROM requests WHERE chat_id=%s AND id=%s""",
                        (int(chat_id), int(request_id)),
                    )
                    return cur.fetchone()
        with _sqlite() as conn:
            item = conn.execute(
                """SELECT id, link_count, status, created_at
                   FROM requests WHERE chat_id=? AND id=?""",
                (int(chat_id), int(request_id)),
            ).fetchone()
    return dict(item) if item else None


def recent_for_user(chat_id, limit=10):
    maximum = min(max(int(limit), 1), 20)
    with _LOCK:
        if _pg_url():
            from psycopg.rows import dict_row
            with _postgres() as conn:
                with conn.cursor(row_factory=dict_row) as cur:
                    cur.execute(
                        """SELECT id, link_count, status, created_at
                           FROM requests WHERE chat_id=%s ORDER BY id DESC LIMIT %s""",
                        (int(chat_id), maximum),
                    )
                    return cur.fetchall()
        with _sqlite() as conn:
            rows = conn.execute(
                """SELECT id, link_count, status, created_at
                   FROM requests WHERE chat_id=? ORDER BY id DESC LIMIT ?""",
                (int(chat_id), maximum),
            ).fetchall()
    return [dict(row) for row in rows]
