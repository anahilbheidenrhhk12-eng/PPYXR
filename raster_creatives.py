"""Visual text overlays for legitimate promotional PNG/JPG/WEBP templates.

The tool does not read verification identity datasets, change faces, or modify
eligibility documentation. Source artwork stays unmodified on disk.
"""
import hashlib
import io
import json
import os
import re
import secrets
from pathlib import Path

import psycopg
from psycopg.rows import dict_row
from PIL import Image, ImageDraw, ImageFont, ImageOps, UnidentifiedImageError

from creative_templates import FIELDS

SUPPORTED = {".png", ".jpg", ".jpeg", ".webp"}
MAX_BYTES = 20 * 1024 * 1024
MAX_PIXELS = 24_000_000
MAX_LAYERS = 32
FIELD_SET = frozenset(FIELDS)
IMAGE_TYPES = {"PNG", "JPEG", "WEBP"}
FONT_CANDIDATES = (
    "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
    "/usr/share/fonts/truetype/liberation2/LiberationSans-Regular.ttf",
    "/usr/share/fonts/truetype/freefont/FreeSans.ttf",
)
FONT_BOLD = (
    "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
    "/usr/share/fonts/truetype/liberation2/LiberationSans-Bold.ttf",
)
Image.MAX_IMAGE_PIXELS = MAX_PIXELS


def source_path(name):
    if not isinstance(name, str) or not (5 <= len(name) <= 120):
        raise ValueError("Invalid image file name")
    if Path(name).name != name or name[0] == "." or not re.fullmatch(r"[\w .()\-]+", name):
        raise ValueError("Invalid image file name")
    if Path(name).suffix.lower() not in SUPPORTED:
        raise ValueError("The visual editor supports PNG, JPG and WEBP only")
    folder = Path(os.getenv("TEMPLATE_STORAGE_DIR", "/data/templates"))
    file = folder / name
    if not file.is_file() or file.is_symlink():
        raise ValueError("Image template not found")
    if file.stat().st_size > MAX_BYTES:
        raise ValueError("Image exceeds 20 MB")
    return file


def _open(name):
    file = source_path(name)
    try:
        with Image.open(file) as source:
            if source.format not in IMAGE_TYPES:
                raise ValueError("Unsupported image encoding")
            source = ImageOps.exif_transpose(source)
            source.load()
            if source.width < 200 or source.height < 100 or source.width * source.height > MAX_PIXELS:
                raise ValueError("Image dimensions are outside supported limits")
            return source.convert("RGB")
    except (UnidentifiedImageError, OSError, Image.DecompressionBombError) as exc:
        raise ValueError("Image file is invalid or unreadable") from exc


def describe(name):
    file = source_path(name)
    with Image.open(file) as img:
        width, height = ImageOps.exif_transpose(img).size
    if width < 200 or height < 100 or width * height > MAX_PIXELS:
        raise ValueError("Image dimensions are outside supported limits")
    return {
        "name": name, "width": width, "height": height,
        "checksum": hashlib.sha256(file.read_bytes()).hexdigest(),
        "fields": FIELDS,
    }


def _db():
    url = os.getenv("DATABASE_URL", "").strip()
    if not url:
        raise ValueError("PostgreSQL connection is unavailable")
    return psycopg.connect(url, connect_timeout=12)


def init_db():
    with _db() as conn:
        with conn.cursor() as cur:
            cur.execute("""
                CREATE TABLE IF NOT EXISTS creative_raster_mappings (
                    template_name TEXT PRIMARY KEY,
                    source_checksum TEXT NOT NULL,
                    overlays JSONB NOT NULL,
                    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
                )""")
            cur.execute("""
                CREATE TABLE IF NOT EXISTS creative_raster_rows (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    template_name TEXT NOT NULL,
                    contents JSONB NOT NULL,
                    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
                )""")
            cur.execute("""
                CREATE INDEX IF NOT EXISTS creative_raster_rows_template
                ON creative_raster_rows (template_name, id DESC)""")
            cur.execute("""
                CREATE TABLE IF NOT EXISTS creative_raster_sequence (
                    template_name TEXT PRIMARY KEY,
                    last_row_id BIGINT NOT NULL DEFAULT 0
                )""")


def mapping(name):
    source_path(name)
    with _db() as conn:
        with conn.cursor(row_factory=dict_row) as cur:
            cur.execute(
                "SELECT source_checksum, overlays FROM creative_raster_mappings "
                "WHERE template_name=%s", (name,)
            )
            return cur.fetchone()


def _valid_color(value):
    return bool(isinstance(value, str) and re.fullmatch(r"#[a-fA-F0-9]{6}", value))


def validate_overlay(item, seen):
    if not isinstance(item, dict):
        raise ValueError("Invalid visual layer")
    id_ = str(item.get("id", ""))[:40]
    if not re.fullmatch(r"[a-zA-Z0-9_-]{5,40}", id_) or id_ in seen:
        raise ValueError("Duplicated or invalid layer ID")
    seen.add(id_)
    field = item.get("field")
    if field not in FIELD_SET:
        raise ValueError("Please select a supported promotional text field")
    result = {"id": id_, "field": field}
    for prop in ("x", "y", "w", "h"):
        raw = item.get(prop, 0)
        if type(raw) not in (int, float):
            raise ValueError("Layer geometry must be numeric")
        v = round(float(raw), 2)
        if not 0 <= v <= 1000:
            raise ValueError("Layer outside the image")
        result[prop] = v
    if not 15 <= result["w"] <= 1000 or not 15 <= result["h"] <= 1000:
        raise ValueError("Layer must have a visible selection area")
    if result["x"] + result["w"] > 1000.01 or result["y"] + result["h"] > 1000.01:
        raise ValueError("Layer selection must stay inside the image")
    size = item.get("size", 30)
    if type(size) not in (int, float) or not 8 <= size <= 120:
        raise ValueError("Font size must be between 8 and 120")
    result["size"] = round(float(size), 2)
    color = item.get("color", "#FFFFFF")
    if not _valid_color(color):
        raise ValueError("Invalid text color")
    result["color"] = color.upper()
    align = item.get("align", "left")
    if align not in ("left", "center", "right"):
        raise ValueError("Invalid text alignment")
    result["align"] = align
    result["bold"] = item.get("bold") is True
    return result


def save_mapping(name, checksum, overlays):
    info = describe(name)
    if info["checksum"] != checksum:
        raise ValueError("The original image has changed. Reload the editor.")
    if not isinstance(overlays, list) or not 1 <= len(overlays) <= MAX_LAYERS:
        raise ValueError("Choose between 1 and 32 text regions")
    seen = set()
    layers = [validate_overlay(layer, seen) for layer in overlays]
    with _db() as conn:
        with conn.cursor() as cur:
            cur.execute("""
                INSERT INTO creative_raster_mappings
                (template_name, source_checksum, overlays)
                VALUES (%s, %s, %s::jsonb)
                ON CONFLICT (template_name) DO UPDATE
                SET source_checksum=excluded.source_checksum,
                    overlays=excluded.overlays,
                    updated_at=now()
            """, (name, checksum, json.dumps(layers)))
    return layers


def saved_fields(name):
    saved = mapping(name)
    if not saved or saved["source_checksum"] != describe(name)["checksum"]:
        return []
    return list(dict.fromkeys(layer["field"] for layer in saved["overlays"]))


def add_record(name, values):
    fields = saved_fields(name)
    if not fields:
        raise ValueError("Save the visual text regions before adding content")
    contents = {}
    for field in fields:
        value = str(values.get(field, "")).strip()
        if len(value) > 180:
            raise ValueError("Content values may not exceed 180 characters")
        contents[field] = value
    with _db() as conn:
        with conn.cursor() as cur:
            cur.execute(
                "INSERT INTO creative_raster_rows (template_name, contents) "
                "VALUES (%s, %s::jsonb) RETURNING id",
                (name, json.dumps(contents))
            )
            return cur.fetchone()[0]


def records(name, limit=40):
    source_path(name)
    with _db() as conn:
        with conn.cursor(row_factory=dict_row) as cur:
            cur.execute(
                "SELECT id, created_at, contents FROM creative_raster_rows "
                "WHERE template_name=%s ORDER BY id DESC LIMIT %s",
                (name, min(100, max(1, int(limit))))
            )
            return cur.fetchall()


def _contents(name, row_id):
    with _db() as conn:
        with conn.cursor(row_factory=dict_row) as cur:
            cur.execute(
                "SELECT contents FROM creative_raster_rows "
                "WHERE template_name=%s AND id=%s",
                (name, int(row_id))
            )
            row = cur.fetchone()
    if not row:
        raise ValueError("Content record not found")
    return row["contents"]


def _font(size, bold=False):
    choices = (FONT_BOLD if bold else ()) + FONT_CANDIDATES
    for name in choices:
        try:
            return ImageFont.truetype(name, size)
        except OSError:
            continue
    return ImageFont.load_default(size=size)


def _wrap(draw, content, font, max_width):
    # Predictable text wrapping, including non-space-delimited words.
    lines = []
    for raw_line in content.splitlines()[:8]:
        current = ""
        for word in raw_line.split(" "):
            attempt = (current + " " + word).strip()
            if draw.textbbox((0, 0), attempt, font=font)[2] <= max_width:
                current = attempt
                continue
            if current:
                lines.append(current)
            current = word
            while current and draw.textbbox((0, 0), current, font=font)[2] > max_width:
                head, tail = "", current
                for i in range(1, len(current) + 1):
                    if draw.textbbox((0, 0), current[:i], font=font)[2] > max_width:
                        head, tail = current[:max(1, i-1)], current[max(1, i-1):]
                        break
                lines.append(head or tail[:1])
                current = tail if head else tail[1:]
        lines.append(current)
    return lines[:12]


def render(name, row_id):
    cfg = mapping(name)
    if not cfg or cfg["source_checksum"] != describe(name)["checksum"]:
        raise ValueError("Visual regions not configured or image replaced")
    content = _contents(name, row_id)
    image = _open(name)
    draw = ImageDraw.Draw(image)
    for layer in cfg["overlays"]:
        value = str(content.get(layer["field"], ""))[:180]
        if not value:
            continue
        x = round(image.width * layer["x"] / 1000)
        y = round(image.height * layer["y"] / 1000)
        width = round(image.width * layer["w"] / 1000)
        height = round(image.height * layer["h"] / 1000)
        size = max(8, round(image.width * layer["size"] / 1000))
        min_font = max(8, round(image.width * 8 / 1000))
        for _ in range(18):
            font = _font(size, layer["bold"])
            lines = _wrap(draw, value, font, width)
            box = draw.textbbox((0, 0), "Ag", font=font)
            line_height = max(1, box[3]-box[1]+round(size*.25))
            if len(lines)*line_height <= height or size <= min_font:
                break
            size = max(min_font, size-2)
        fill = layer["color"]
        for i, line in enumerate(lines):
            py = y + i*line_height
            if py + line_height > y + height:
                break
            measured = draw.textbbox((0, 0), line, font=font)[2]
            px = x
            if layer["align"] == "center":
                px += max(0, (width-measured)//2)
            elif layer["align"] == "right":
                px += max(0, width-measured)
            draw.text((px, py), line, font=font, fill=fill)
    output = io.BytesIO()
    image.save(output, "PNG", optimize=True)
    return output.getvalue()


def next_version(name):
    saved = mapping(name)
    if not saved:
        raise ValueError("Configure text regions first")
    with _db() as conn:
        with conn.cursor() as cur:
            cur.execute(
                "INSERT INTO creative_raster_sequence(template_name,last_row_id) "
                "VALUES (%s,0) ON CONFLICT DO NOTHING", (name,)
            )
            cur.execute(
                "SELECT last_row_id FROM creative_raster_sequence "
                "WHERE template_name=%s FOR UPDATE", (name,)
            )
            previous = cur.fetchone()[0]
            cur.execute(
                "SELECT id FROM creative_raster_rows "
                "WHERE template_name=%s AND id>%s ORDER BY id LIMIT 1",
                (name, previous)
            )
            row = cur.fetchone()
            if not row:
                cur.execute(
                    "SELECT id FROM creative_raster_rows "
                    "WHERE template_name=%s ORDER BY id LIMIT 1", (name,)
                )
                row = cur.fetchone()
            if not row:
                raise ValueError("Add some content records before generating versions")
            cur.execute(
                "UPDATE creative_raster_sequence SET last_row_id=%s "
                "WHERE template_name=%s", (row[0], name)
            )
            row_id = row[0]
    return row_id, render(name, row_id)
